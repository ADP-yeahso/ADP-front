import 'package:flutter/material.dart';

enum CareActivityKind { letter, manual, guided }

class CareActivity {
  const CareActivity(
    this.id,
    this.title,
    this.description,
    this.icon, {
    this.kind = CareActivityKind.guided,
  });

  final String id;
  final String title;
  final String description;
  final IconData icon;
  final CareActivityKind kind;
  bool get isCommon => kind != CareActivityKind.guided;
}

class CareActivityGroup {
  const CareActivityGroup(this.label, this.color, this.activities);

  final String label;
  final Color color;
  final List<CareActivity> activities;
}

