  static CareActivityGroup? groupFor(String? emotionCode) {
    final code = emotionCode?.trim().toLowerCase();
    // The existing frontend calls the backend's tenderness "affection".
    return _byEmotion[code == 'affection' ? 'tenderness' : code];
  }

  static List<CareActivity> activitiesFor(String? emotionCode) =>
      List.unmodifiable([...common, ...?groupFor(emotionCode)?.activities]);
